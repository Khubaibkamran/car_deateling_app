"""Turns downloaded Figma SVGs into a TypeScript module of raw SVG strings.

Usage:  python scripts/svg_to_ts.py <out.ts> NAME=file.svg [NAME=file.svg ...]
Each SVG is cleaned (ids / inline styles / preserveAspectRatio removed) and exported as `export const NAME_XML`.
"""
import re
import sys


def clean(svg: str) -> str:
    svg = re.sub(r'\sstyle="[^"]*"', "", svg)
    svg = re.sub(r'\sid="[^"]*"', "", svg)
    svg = svg.replace('preserveAspectRatio="none" ', "").replace('overflow="visible" ', "")
    return svg.strip().replace("\n", "")


def main() -> None:
    out, *pairs = sys.argv[1:]
    lines = ["// Generated by scripts/svg_to_ts.py - raw SVG strings for icons with long path data.", ""]
    for pair in pairs:
        name, url = pair.split("=", 1)
        with open(url, encoding="utf-8") as f:
            svg = clean(f.read())
        lines.append(f"export const {name}_XML = `{svg}`;")
        lines.append("")
        print(name, len(svg))
    with open(out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))


if __name__ == "__main__":
    main()
